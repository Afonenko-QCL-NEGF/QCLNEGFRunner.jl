# Unit conversion at the Runner boundary, retaining IEEE values and dimensions.
_runner_electronvolts(q) = Float64(ustrip(u"eV", q))
_runner_metres(q) = Float64(ustrip(u"m", q))
_runner_kelvin(q) = Float64(ustrip(u"K", q))
_runner_inverse_metres(q) = Float64(ustrip(u"m^-1", q))
_runner_volts_per_metre(q) = Float64(ustrip(u"V/m", q))
_runner_per_square_metre(q) = Float64(ustrip(u"m^-2", q))

_physical_sheet_density_matrix(problem, green) = ustrip.(u"m^-2", QCLNEGF.sheet_density_matrix(problem, green))

_runner_current_A_per_cm2(value::Real) = Float64(ustrip(u"A/cm^2", uconvert(u"A/cm^2", value*u"A/m^2")))
